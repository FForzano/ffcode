"""Multi-repo workspace: several repositories that make up one product. Config: .ffcode/workspace.toml
  workspace.py status | sync [NAME..] [--from-local] | graph | map | where NAME | contracts [--changed] [--accept]
workspace.toml:
  [[repo]]  name, url, role (frontend|backend|infra|docs|...), branch (default main),
            local (optional path of an existing checkout, used by --from-local),
            depends_on (list of names), contracts (list of paths inside that repo: OpenAPI, schemas, env examples)
Clones go to .ffcode/repos/<name> (git-ignored by .ffcode/.gitignore). 'self' marks the repo holding .ffcode/."""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import tomllib
from pathlib import Path

from common import DIRNAME, die, find_root, git


def load(root: Path):
    f = root / DIRNAME / "workspace.toml"
    if not f.is_file(): die(f"no {f}; copy templates/workspace.toml from ffcode-core")
    repos = tomllib.loads(f.read_text()).get("repo", [])
    for r in repos:
        r.setdefault("branch", "main"); r.setdefault("depends_on", []); r.setdefault("contracts", [])
        r["path"] = root if r.get("self") else root / DIRNAME / "repos" / r["name"]
    return repos


def info(r):
    p = r["path"]
    if not (p / ".git").exists(): return "missing", ""
    _, br = git(["rev-parse", "--abbrev-ref", "HEAD"], p)
    _, dirty = git(["status", "--porcelain"], p)
    _, ab = git(["rev-list", "--left-right", "--count", f"HEAD...@{{u}}"], p)
    ahead, behind = (ab.split() + ["?", "?"])[:2] if ab.strip() and "fatal" not in ab else ("?", "?")
    return br.strip(), f"{'dirty ' if dirty.strip() else 'clean '}ahead {ahead} behind {behind}"


def cmd_status(repos):
    for r in repos:
        br, st = info(r)
        flag = "" if br in ("missing", r["branch"]) else f"  (expected {r['branch']})"
        print(f"{r['name']:28}{r.get('role', ''):10}{br:16}{st}{flag}")


def cmd_sync(repos, names, from_local):
    for r in repos:
        if names and r["name"] not in names or r.get("self"): continue
        p = r["path"]
        if not (p / ".git").exists():
            p.parent.mkdir(parents=True, exist_ok=True)
            src = r.get("local") if from_local and r.get("local") and Path(r["local"]).expanduser().is_dir() else r["url"]
            rc, out = git(["clone", str(Path(src).expanduser()) if src != r["url"] else src, str(p)], p.parent)
            if rc == 0 and src != r["url"]: git(["remote", "set-url", "origin", r["url"]], p)
            if rc == 0: git(["checkout", r["branch"]], p)
            print(f"clone {r['name']}: {'ok' if rc == 0 else 'FAILED ' + out.strip()[-200:]}")
        else:
            _, dirty = git(["status", "--porcelain"], p)
            if dirty.strip(): print(f"skip  {r['name']}: local changes"); continue
            rc, out = git(["pull", "--ff-only"], p)
            print(f"pull  {r['name']}: {'ok' if rc == 0 else 'FAILED ' + out.strip()[-200:]}")


def cmd_graph(repos):
    names = {r["name"] for r in repos}
    for r in repos:
        deps = ", ".join(d if d in names else f"{d}?" for d in r["depends_on"]) or "-"
        print(f"{r['name']} [{r.get('role', '')}] -> {deps}")


def contract_hashes(repos):
    new = {}
    for r in repos:
        for c in r["contracts"]:
            f = r["path"] / c
            new[f"{r['name']}:{c}"] = hashlib.sha1(f.read_bytes()).hexdigest()[:12] if f.is_file() else "missing"
    return new


def cmd_contracts(root, repos, changed, accept):
    """Compare the contract files with .ffcode/contracts.lock (committed: the versions the repos last agreed on). --accept rewrites the lock."""
    lock = root / DIRNAME / "contracts.lock"
    old = json.loads(lock.read_text()) if lock.is_file() else {}
    new = contract_hashes(repos)
    for k, v in new.items():
        state = "NEW" if k not in old else "CHANGED" if old[k] != v else ""
        if not changed or state: print(f"{v}  {k}  {state}".rstrip())
    for k in old.keys() - new.keys(): print(f"-             {k}  REMOVED")
    if accept:
        lock.write_text(json.dumps(new, indent=1, sort_keys=True) + "\n"); print(f"lock updated: {lock}")
    elif not lock.is_file(): print("no contracts.lock yet: `ff workspace contracts --accept` records the current versions")


def cmd_map(root, repos):
    """.ffcode/workspace-map.md: repos, roles, dependents, contracts with hash, env keys of the env-example contracts, top-level layout of each clone."""
    names = {r["name"] for r in repos}
    dependents = {n: [r["name"] for r in repos if n in r["depends_on"]] for n in names}
    hashes = contract_hashes(repos)
    lines = [f"# Workspace map of {root.name} (generated by `ff workspace map`, do not edit)", ""]
    for r in repos:
        br, st = info(r)
        lines += [f"## {r['name']} [{r.get('role', '')}]" + (" (this repo)" if r.get("self") else ""),
                  f"- branch {r['branch']}; local: {br} {st}".rstrip(),
                  f"- depends on: {', '.join(r['depends_on']) or '-'}; used by: {', '.join(dependents[r['name']]) or '-'}"]
        for c in r["contracts"]:
            lines.append(f"- contract `{c}` ({hashes[r['name'] + ':' + c]})")
            f = r["path"] / c
            if f.is_file() and re.search(r"env", f.name, re.I):
                keys = sorted({m.group(1) for l in f.read_text(errors="replace").splitlines() if (m := re.match(r"\s*(?:export\s+)?([A-Z][A-Z0-9_]+)\s*=", l))})
                if keys: lines.append(f"  env: {', '.join(keys)}")
        if (r["path"] / ".git").exists():
            top = sorted(p.name + ("/" if p.is_dir() else "") for p in r["path"].iterdir() if not p.name.startswith(".") and p.name not in ("node_modules", "vendor", "__pycache__"))
            lines.append("- top level: " + ", ".join(top[:25]))
        lines.append("")
    out = root / DIRNAME / "workspace-map.md"; out.write_text("\n".join(lines)); print(f"wrote {out}")


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("cmd", choices=["status", "sync", "graph", "where", "contracts", "map"])
    ap.add_argument("names", nargs="*"); ap.add_argument("--root"); ap.add_argument("--from-local", action="store_true")
    ap.add_argument("--changed", action="store_true"); ap.add_argument("--accept", action="store_true")
    a = ap.parse_args(); root = find_root(a.root); repos = load(root)
    if a.cmd == "status": cmd_status(repos)
    elif a.cmd == "sync": cmd_sync(repos, a.names, a.from_local); cmd_map(root, repos)
    elif a.cmd == "graph": cmd_graph(repos)
    elif a.cmd == "contracts": cmd_contracts(root, repos, a.changed, a.accept)
    elif a.cmd == "map": cmd_map(root, repos)
    elif a.cmd == "where":
        for r in repos:
            if r["name"] in a.names: print(r["path"])


if __name__ == "__main__":
    sys.exit(main())
