"""Decision records in .ffcode/decisions/ with a generated index.
  adr.py "Title" [--rules S6,FUNC] [--supersedes 0002]   new record (marks the superseded one), then refreshes index.md
  adr.py --list [--rule ID] [--grep TEXT]                  one line per record: number, status, rules, title (accepted ones only unless --all)
  adr.py --index                                           regenerate decisions/index.md
Header line of a record: `Date: D  Status: accepted  Rules: S6, FUNC  Supersedes: 0002` (Rules and Supersedes optional).
A rule that the decision changes for the scripts also goes in .ffcode/rules.toml with `adr = "NNNN"`."""
from __future__ import annotations

import argparse
import datetime
import re

from common import DIRNAME, find_root

HEAD = re.compile(r"^Date:.*$", re.M)


def records(d):
    out = []
    for f in sorted(d.glob("[0-9]*-*.md")):
        t = f.read_text()
        title = re.search(r"^# \d+\s+(.+)$", t, re.M)
        st = re.search(r"Status:\s*([^\n]*?)(?:\s{2,}|$|\n)", t)
        rules = re.search(r"Rules:\s*([^\n]*?)(?:\s{2,}|$|\n)", t)
        out.append({"n": f.name[:4], "file": f.name, "title": title.group(1) if title else f.stem,
                    "status": st.group(1).strip() if st else "accepted",
                    "rules": [r.strip() for r in rules.group(1).split(",") if r.strip()] if rules else []})
    return out


def write_index(d):
    rs = records(d)
    lines = ["# Decisions (generated by `ff adr`, do not edit)", "", "| # | Status | Rules | Title |", "|---|---|---|---|"]
    lines += [f"| [{r['n']}]({r['file']}) | {r['status']} | {', '.join(r['rules']) or '-'} | {r['title']} |" for r in rs]
    (d / "index.md").write_text("\n".join(lines) + "\n")


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("title", nargs="?"); ap.add_argument("--root")
    ap.add_argument("--rules", default=""); ap.add_argument("--supersedes")
    ap.add_argument("--list", action="store_true"); ap.add_argument("--all", action="store_true"); ap.add_argument("--rule"); ap.add_argument("--grep")
    ap.add_argument("--index", action="store_true")
    a = ap.parse_args(); d = find_root(a.root) / DIRNAME / "decisions"; d.mkdir(parents=True, exist_ok=True)
    if a.list:
        for r in records(d):
            if not a.all and not r["status"].startswith("accepted"): continue
            if a.rule and a.rule.upper() not in r["rules"]: continue
            if a.grep and a.grep.lower() not in (r["title"] + (d / r["file"]).read_text()).lower(): continue
            print(f"{r['n']} {r['status']:<10} {','.join(r['rules']) or '-':<12} {r['title']}")
        return 0
    if a.index or not a.title:
        write_index(d); print(d / "index.md"); return 0
    n = 1 + max([int(m.group(1)) for f in d.glob("*.md") if (m := re.match(r"(\d+)-", f.name))] or [0])
    slug = re.sub(r"[^a-z0-9]+", "-", a.title.lower()).strip("-")[:50]
    p = d / f"{n:04d}-{slug}.md"
    head = f"Date: {datetime.date.today()}  Status: accepted"
    rules = ", ".join(r.strip().upper() for r in a.rules.split(",") if r.strip())
    if rules: head += f"  Rules: {rules}"
    if a.supersedes:
        old = next(iter(d.glob(f"{int(a.supersedes):04d}-*.md")), None)
        if old:
            old.write_text(re.sub(r"Status:\s*\w+", f"Status: superseded by {n:04d}", old.read_text(), count=1))
            head += f"  Supersedes: {int(a.supersedes):04d}"
    p.write_text(f"# {n:04d} {a.title}\n\n{head}\n\n## Context\n\n## Decision\n\n## Consequences\n\n## Alternatives rejected\n")
    write_index(d); print(p)
    return 0
