"""Compact repo map + symbol index, to avoid re-exploring the tree.
  mapper.py build [--root DIR] [--out FILE|-] [--max-symbols N]   write .ffcode/map.md and cache/symbols.json
  mapper.py find NAME [--root DIR]                                symbols whose name contains NAME (file:line)"""
from __future__ import annotations

import argparse
import json
import re
from collections import defaultdict
from pathlib import Path

from common import DIRNAME, find_root, is_text, lang_of, load_config, tracked_files

SYM = {
    "python": re.compile(r"^(?:async\s+)?(class|def)\s+(\w+)"),
    "php": re.compile(r"^\s*(?:abstract\s+|final\s+)?(class|interface|trait|function)\s+(\w+)|^\s*(?:public|protected|private)\s+(?:static\s+)?function\s+()(\w+)"),
    "typescript": re.compile(r"^export\s+(?:default\s+)?(?:async\s+)?(class|function|const|interface|type|enum)\s+(\w+)"),
    "javascript": re.compile(r"^export\s+(?:default\s+)?(?:async\s+)?(class|function|const)\s+(\w+)"),
    "matlab": re.compile(r"^\s*(function|classdef)\s+(?:.*=\s*)?(\w+)"),
    "shell": re.compile(r"^(function\s+)?(\w+)\s*\(\)\s*\{|^(function)\s+(\w+)"),
    "terraform": re.compile(r'^(resource|module|variable|output)\s+"([^"]+)"(?:\s+"([^"]+)")?'),
}
ENTRY = {"main.py", "__main__.py", "cli.py", "manage.py", "index.php", "yii", "index.ts", "index.tsx", "App.tsx",
         "main.tf", "Dockerfile", "docker-compose.yml", "Makefile", "package.json", "pyproject.toml", "composer.json"}


def symbols(path: Path, lang: str):
    rx = SYM.get(lang)
    if not rx:
        return []
    out = []
    for i, line in enumerate(path.read_text(errors="replace").splitlines(), 1):
        m = rx.match(line)
        if m:
            g = [x for x in m.groups() if x]
            kind, name = (g[0], g[-1]) if len(g) > 1 else ("def", g[0])
            if name and not name.startswith("__"):
                out.append((i, kind.strip(), name))
    return out


def build(root: Path, max_symbols: int, max_lines: int = 400):
    files = [f for f in tracked_files(root) if is_text(root / f)]
    idx, per_dir, entries = {}, defaultdict(lambda: [0, 0]), []
    for f in files:
        p = root / f
        n = sum(1 for _ in p.open(errors="replace"))
        top = "/".join(f.parts[:2]) if len(f.parts) > 2 else (f.parts[0] if len(f.parts) > 1 else ".")
        per_dir[top][0] += 1; per_dir[top][1] += n
        if f.name in ENTRY: entries.append(str(f))
        lang = lang_of(f)
        if lang in SYM:
            s = symbols(p, lang)
            if s: idx[str(f)] = s
    lines = [f"# Map of {root.name} (generated by ffcode, do not edit)", "",
             "## Layout (dir: files, lines)"]
    lines += [f"- {d}: {c[0]}f {c[1]}l" for d, c in sorted(per_dir.items())]
    if entries:
        lines += ["", "## Entry points / manifests"] + [f"- {e}" for e in sorted(entries)[:40]]
    cfg = load_config(root)
    if cfg["commands"]:
        lines += ["", "## Commands"] + [f"- {k}: `{v}`" for k, v in cfg["commands"].items()]
    lines += ["", "## Symbols (file: name@line)"]
    for f, syms in sorted(idx.items()):
        shown = syms[:max_symbols]
        more = f" (+{len(syms) - len(shown)})" if len(syms) > len(shown) else ""
        lines.append(f"- {f}: " + ", ".join(f"{n}@{i}" for i, _, n in shown) + more)
    if len(lines) > max_lines:
        lines = lines[:max_lines] + [f"... truncated ({len(lines) - max_lines} lines); use `ffcode find NAME`"]
    return "\n".join(lines) + "\n", idx


def main():
    ap = argparse.ArgumentParser()
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build"); b.add_argument("--root"); b.add_argument("--out"); b.add_argument("--max-symbols", type=int, default=12)
    f = sub.add_parser("find"); f.add_argument("name"); f.add_argument("--root")
    a = ap.parse_args()
    root = find_root(a.root)
    cache = root / DIRNAME / "cache" / "symbols.json"
    if a.cmd == "build":
        text, idx = build(root, a.max_symbols)
        if a.out == "-":
            print(text); return
        out = Path(a.out) if a.out else root / DIRNAME / "map.md"
        out.parent.mkdir(parents=True, exist_ok=True); out.write_text(text)
        if not a.out:
            cache.parent.mkdir(parents=True, exist_ok=True)
            cache.write_text(json.dumps({f: [[i, k, n] for i, k, n in s] for f, s in idx.items()}))
            import indexes
            indexes.build_all(root, [f for f in tracked_files(root) if is_text(root / f)])
        print(f"wrote {out} ({len(text.splitlines())} lines, {len(idx)} files with symbols)")
    else:
        if not cache.is_file():
            _, idx = build(root, 10**6)
            idx = {f: [list(x) for x in s] for f, s in idx.items()}
        else:
            idx = json.loads(cache.read_text())
        q = a.name.lower(); hit = 0
        gl = root / DIRNAME / "glossary.md"
        if gl.is_file():
            for l in gl.read_text().splitlines():
                if q in l.lower() and l.startswith(("|", "- ")) and not l.startswith("|--"): print(f"glossary: {l.strip()}"); hit += 1
        for f, syms in sorted(idx.items()):
            for i, k, n in syms:
                if q in n.lower():
                    print(f"{f}:{i}: {k} {n}"); hit += 1
        if not hit: print("no match")


if __name__ == "__main__":
    main()
